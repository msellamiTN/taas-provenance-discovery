"""Generate docs/RESULTS.md from results/*.json so every reported number is traceable to a file."""
from __future__ import annotations

import json

from common import RESULTS, ROOT


def L(name):
    return json.load(open(RESULTS / f"{name}.json"))


def f3(x):
    return f"{x:.3f}"


def main() -> None:
    e0, e2, e3, tune, e4, e5, e6, e7 = (L(n) for n in ("e0_registry", "e2_eligibility", "e3_gap_sonnet", "e3_tune",
                                                       "e4_injection", "e5_synthetic", "e6_ablations",
                                                       "e7_scalability"))
    cal = L("calibration_table")
    out = []
    w = out.append
    w("# Results\n")
    w("All numbers below are generated by `experiments/report.py` from `results/*.json` "
      "(produced by `experiments/run_all.py`). Mean ± 95% CI (normal approximation) where seeds or tasks vary.\n")

    # E0
    t1 = e0["table1"]
    w("## E0 — Registry characterisation (Table 1, §2.2)\n")
    w("| Registry | Servers | Tools | Annotated | Paper |\n|---|---|---|---|---|")
    for k, ref in (("LiveMCPTool", "69 / 525 / 44"), ("MCPToolBench++", "10 / 87 / 0"), ("merged", "76 / 569 / 44")):
        w(f"| {k} | {t1[k]['servers']} | {t1[k]['tools']} | {t1[k]['annotated']} | {ref} |")
    w("")
    w(f"* Annotated tools all claim `readOnlyHint=true`: **{e0['annotated_all_claim_read_only']}**; "
      f"annotated but not read-only (silver labels): **{len(e0['annotated_but_not_read_only_silver'])}** "
      f"(`{', '.join(e0['annotated_but_not_read_only_silver'])}`; paper: 1).")
    w(f"* Tools that modify state: silver **{e0['modify_state_silver']['count']} "
      f"({e0['modify_state_silver']['share']:.1%})**, lexical labeller **{e0['modify_state_lexical']['count']} "
      f"({e0['modify_state_lexical']['share']:.1%})**; paper 158 (27.8%). Lexical vs silver: precision "
      f"{f3(e0['lexical_vs_silver']['precision'])}, recall {f3(e0['lexical_vs_silver']['recall'])}.")
    w(f"* Requiring declared read-only hints keeps **{e0['require_declared_read_only_keeps']['share']:.1%}** "
      f"of the registry (paper 7.7%); the closed-world annotation filter removes "
      f"**{e0['closed_world_ann_filters']}** tools.")
    w(f"* MCPToolBench++ public release: {e0['requests']['MCPToolBench++']} requests "
      f"({e0['requests']['MCPToolBench++_unique_queries']} unique queries) vs 1,429 in Table 1.\n")

    # calibration
    w("## Measured ρ_LLM profiles (Definition 6)\n")
    w("Accuracy per class and input size n (4 items per cell, answered by reading only).\n")
    w("| Model | Class | " + " | ".join(f"n={n}" for n in (10, 40, 160, 640)) + " |\n|---|---|---|---|---|---|")
    for m, t in cal.items():
        for c, d in t.items():
            w(f"| {m} | {c} | " + " | ".join(f"{d[str(n)]:.2f}" for n in (10, 40, 160, 640)) + " |")
    w("\n![ρ calibration](../results/figures/rho_calibration.png)\n")

    # E2
    s = e2["summary"]
    encs = ["ann+", "ann-cw", "lex+", "lex-cw", "obs+", "att+"]
    w("## E2 — H2: provenance-sound eligibility under forged and missing metadata\n")
    w("Exposure = share of truly unsafe tools admitted by a read-only policy (5 seeds). "
      "Metadata-only encodings (ann/lex) are evaluated on what an MCP client holds; obs/att on a registry "
      "with sandbox evidence (verifier FAR) and attestations for 30% of tools.\n")
    w("| α forged | FAR | " + " | ".join(encs) + " |\n|---|---|" + "---|" * len(encs))
    for a in (0.0, 0.25, 0.5):
        for far in (0.0, 0.05, 0.2):
            w(f"| {a} | {far} | " + " | ".join(f3(s[f'a={a}|far={far}|{e}']['exposure']['mean']) for e in encs) + " |")
    m = {e: s[f"a=0.25|far=0.05|{e}"] for e in encs}
    w("\nAt α = 0.25, FAR = 0.05 — safe retention: " +
      ", ".join(f"{e} {m[e]['safe_retention']['mean']:.2f}" for e in encs) + ".\n")
    w("![H2](../results/figures/h2_exposure.png)\n")

    # E3 tune + E3
    w("## E3 — H3: gap analysis shrinks toolkits\n")
    w(f"Dev-split tuning (MCPToolBench++ sample, 60 queries) selected **{tune['selected']}**. "
      "Pure Eq. 6 (w_rel = 0) loses recall as K grows:\n")
    w("| K | " + " | ".join(f"w_rel={r}" for r in (0.0, 1.0, 3.0, 10.0)) + " |\n|---|---|---|---|---|")
    for K in (3, 5, 10):
        w(f"| {K} | " + " | ".join(f3(tune['grid'][f'K={K}|rel={r}']['recall']['mean']) for r in (0.0, 1.0, 3.0, 10.0)) + " |")
    w("\n![tuning](../results/figures/tune_relevance.png)\n")
    systems = ["ours", "ours-nogap", "ours-strict", "per-subtask", "per-subtask-gap", "rag-top3", "rag-top5",
               "mcp-zero", "all-tools"]
    for src, note in (("LiveMCPBench", "test split, 95 tasks"), ("MCPToolBench++", "dev split, 60 queries")):
        w(f"**{src}** ({note}; analyst: recorded Claude Sonnet)\n")
        w("| System | |K| | tokens | gold recall | boundary recall | precision | abstain | certified |\n"
          "|---|---|---|---|---|---|---|---|")
        for sy in systems:
            x = e3["summary"].get(f"{src}|{sy}")
            if not x:
                continue
            w(f"| {sy} | {x['size']['mean']:.2f} | {x['tokens']['mean']:.0f} | {f3(x['recall']['mean'])} ± "
              f"{x['recall']['ci95']:.3f} | {f3(x['boundary_recall']['mean'])} | {f3(x['precision']['mean'])} | "
              f"{x['abstain_rate']:.2f} | {x['valid_rate']:.2f} |")
        w("")
    w("![H3](../results/figures/h3_tokens_vs_recall.png)\n")

    # E4
    w("## E4 — H4: injected actions and Property 1\n")
    w("Worst-case success of injected actions whose effect class the task does not need "
      "(least-privilege policy per task, evidence ≥ ℓobs).\n")
    w("| System | ASR worst (out of scope) | ASR stochastic | gold recall | |K| |\n|---|---|---|---|---|")
    for n, x in e4["summary"].items():
        w(f"| {n} | {f3(x['ASR_worst_out']['mean'])} | {f3(x['ASR_stoch_out']['mean'])} | {f3(x['recall']['mean'])} | "
          f"{x['size']['mean']:.1f} |")
    w("\nProperty 1 — random call sequences over certified toolkits, true effects:\n")
    w("| Certification | effect-bound violations | flow violations | sequences |\n|---|---|---|---|")
    for k, v in e4["property1"].items():
        w(f"| {k} | {v['effect_violations']} | {v['flow_violations']} | {v['sequences']} |")
    w("\n![H4](../results/figures/h4_injection.png)\n")

    # E5
    w("## E5 — Composition on synthetic typed registries (RQ3)\n")
    w("Independent checker; optimum by brute force; 48 tasks (L ∈ {2,3,4} × distractors ∈ {3,5} × 8 seeds).\n")
    w("| System | valid | optimal | cost / optimum | |K| | abstain | time (ms) |\n|---|---|---|---|---|---|---|")
    for n, x in e5["summary"].items():
        w(f"| {n} | {x['valid_rate']:.3f} | {x['optimal_rate']:.3f} | {x['opt_ratio']['mean']:.3f} | "
          f"{x['size']['mean']:.2f} | {x['abstain_rate']:.2f} | {x['time_s']['mean'] * 1000:.1f} |")
    w("")

    # E6
    w("## E6 — Ablations\n")
    w("**Retrieval components** on all 1,509 MCPToolBench++ requests (raw queries):\n")
    w("| Retriever | R@1 | R@3 | R@5 |\n|---|---|---|---|")
    for n, x in e6["retrieval"].items():
        w(f"| {n} | {f3(x['R@1'])} | {f3(x['R@3'])} | {f3(x['R@5'])} |")
    w("\n**Request path** on the LiveMCPBench test split:\n")
    w("| Variant | gold recall | |K| | abstain | certified |\n|---|---|---|---|---|")
    for n, x in e6["path"].items():
        w(f"| {n} | {f3(x['recall']['mean'])} | {x['size']['mean']:.2f} | {x['abstain']:.2f} | {x['valid']:.2f} |")
    sz = e6["sanitisation"]
    w(f"\n**Manifest sanitisation**: poisoned descriptions reaching the model — raw tool list "
      f"{sz['leaked_raw']}/{sz['poisoned']}, sanitised manifest {sz['leaked_sanitised']}/{sz['poisoned']}; "
      f"tokens per tool {sz['tokens_per_tool_raw']:.0f} → {sz['tokens_per_tool_sanitised']:.0f}.\n")

    # E7
    w("## E7 — Evolution and cost (RQ4)\n")
    w("| Tools | bitmap eligibility (µs) | naive scan (µs) | speed-up |\n|---|---|---|---|")
    for n, x in e7["latency"].items():
        w(f"| {int(n):,} | {x['bitmap_us']:.1f} | {x['naive_us']:.0f} | ×{x['speedup']:.0f} |")
    c = e7["prop3"]["confusion"]
    w(f"\n* Prop. 3: changed & invalidated {c['changed&invalidated']}, changed & kept {c['changed&kept']}, "
      f"unchanged & invalidated {c['same&invalidated']}, unchanged & kept {c['same&kept']}; stale answers "
      f"{e7['prop3']['stale']}.")
    w(f"* Lemma 1: {e7['lemma1']['violations']}/{e7['lemma1']['trials']} violations.")
    mt = e7["maintenance"]
    w(f"* Maintenance: incremental `list_changed` {mt['incremental_ms']:.1f} ms vs full rebuild "
      f"{mt['full_rebuild_s']:.2f} s. Rug pull on `{mt['rug_pull']['tool']}`: evidence strength "
      f"{mt['rug_pull']['strength_before']:.2f} → {mt['rug_pull']['strength_after']:.2f} "
      f"({mt['rug_pull']['evidence_after']}); after reverting to the verified definition: "
      f"{mt['rug_pull']['evidence_after_revert']}.\n")
    w("![latency](../results/figures/eligibility_latency.png)\n")
    # E8 (optional: present when experiments/e8_mcpbench_adapter.py has been run)
    e8 = {lab: L(f"e8_mcpbench_adapter_{lab}") for lab in ("codex", "fixed")
          if (RESULTS / f"e8_mcpbench_adapter_{lab}.json").exists()}
    if e8:
        w("## E8 — MCP-Bench integration path, offline (TaaSMCPBenchAdapter.select)\n")
        w("525-tool LiveMCPTool catalogue in MCP-Bench's tool-map shape, 95 LiveMCPBench tasks, recorded "
          "analyst runs (Claude Sonnet). *Abstain* follows the runner patch: an engine abstention or an "
          "empty selection skips the agent. Recall counts an abstained task as 0. RO = the 57 tasks whose "
          "gold tools are all read-only (silver labels).\n")
        w("| Code | Analyst | Contract typing | Policy | abstain | gold recall | recall when run | |K| when run | "
          "RO abstain | RO recall |\n|---|---|---|---|---|---|---|---|---|---|")
        for lab, d in e8.items():
            for k, m in d["summary"].items():
                an, ty, po = k.split("|")
                w(f"| {lab} | {an} | {ty} | {po} | {m['runner_abstain']:.2f} | {f3(m['recall'])} | "
                  f"{f3(m['recall_when_run'])} | {m['size_when_run']:.2f} | {m['read_only_runner_abstain']:.2f} | "
                  f"{f3(m['read_only_recall'])} |")
        w("")
    (ROOT / "docs" / "RESULTS.md").write_text("\n".join(out) + "\n")
    print("wrote docs/RESULTS.md")


if __name__ == "__main__":
    main()
