"""Build a self-contained folder (and zip) of the journal version of Section 8 for Overleaf.

Output: paper/overleaf/evaluation_tsc/ and paper/overleaf/evaluation_tsc.zip, containing
  evaluation_tsc.tex   the section, tables inlined, figure paths relative to the project root
  figures/*.pdf        the six figures it uses (vector)
  evaluation_tsc.bib   the bibliography entries it cites
  ../evaluation_tsc_test.tex  compiles the section alone (IEEEtran, as on Overleaf), at the zip root
  README.txt           how to include it in paper.tex
Usage: python paper/package_overleaf.py
"""
from __future__ import annotations

import re
import shutil
import zipfile
from pathlib import Path

PAPER = Path(__file__).resolve().parent
SRC = PAPER / "sections" / "evaluation_tsc.tex"   # edited journal version (tables inlined)
NAME = "evaluation_tsc"
OUT = PAPER / "overleaf" / NAME


def bib_entries(keys: set[str]) -> str:
    text = (PAPER / "evaluation_final.bib").read_text()
    out = []
    for m in re.finditer(r"@\w+\s*\{\s*([^,\s]+)\s*,.*?\n\}", text, re.S):
        if m.group(1) in keys:
            out.append(m.group(0))
    missing = keys - {re.match(r"@\w+\s*\{\s*([^,\s]+)", e).group(1) for e in out}
    if missing:
        raise SystemExit(f"missing bib entries: {missing}")
    return "\n\n".join(out) + "\n"


def main() -> None:
    if OUT.exists():
        shutil.rmtree(OUT)
    (OUT / "figures").mkdir(parents=True)
    tex = SRC.read_text()
    # inline generated tables
    tex = re.sub(r"\\input\{(tables_r2/[^}]+)\}",
                 lambda m: (PAPER / f"{m.group(1)}.tex").read_text().rstrip() + "\n", tex)
    # figures: copy and point to <folder>/figures/
    figs = re.findall(r"\\includegraphics(\[[^\]]*\])?\{([^}]+)\}", tex)
    for _, stem in figs:
        stem = stem.rsplit("/", 1)[-1]
        shutil.copy2(PAPER / "figures_r2" / f"{stem}.pdf", OUT / "figures" / f"{stem}.pdf")
    tex = re.sub(r"\\includegraphics(\[[^\]]*\])?\{([^}]+)\}",
                 lambda m: f"\\includegraphics{m.group(1) or ''}{{{NAME}/figures/{m.group(2).rsplit('/', 1)[-1]}}}", tex)
    head = (f"% {NAME}.tex -- Section 8 (Experimental Evaluation), journal version, 6-page budget.\n"
            f"% Include from paper.tex with \\input{{{NAME}/{NAME}}}; needs graphicx, booktabs, amsmath, url.\n"
            "% Generated by paper/package_overleaf.py from paper/sections/evaluation_tsc.tex\n"
            "% (repository msellamiTN/taas-provenance-discovery, branch research/pamcp-final-evaluation).\n"
            "\\providecommand{\\pamcp}{PaMCP}\n")
    tex = head + "\n".join(l for l in tex.splitlines() if not l.startswith("% ===")
                           and not l.startswith("% Section 8, journal") and not l.startswith("% Figures: paper/")
                           and not l.startswith("% Every number is read")) + "\n"
    (OUT / f"{NAME}.tex").write_text(tex)
    keys = set()
    for c in re.findall(r"\\cite\{([^}]+)\}", tex):
        keys |= {k.strip() for k in c.split(",")}
    (OUT / f"{NAME}.bib").write_text(bib_entries(keys))
    (OUT.parent / f"{NAME}_test.tex").write_text(rf"""% Optional check: compiles the section alone. Keep it in the project root, next to the folder {NAME}/,
% and set it as the main document (Overleaf: Menu > Main document). Numbered as Section 8 from page 13.
\documentclass[10pt,journal,compsoc]{{IEEEtran}}
\usepackage[nocompress]{{cite}}
\usepackage{{graphicx}}
\usepackage{{booktabs}}
\usepackage{{amsmath,amssymb}}
\usepackage{{url}}
\newcommand{{\pamcp}}{{PaMCP}}
\begin{{document}}
\setcounter{{section}}{{7}}
\setcounter{{figure}}{{7}}
\setcounter{{table}}{{6}}
\setcounter{{page}}{{13}}
\input{{{NAME}/{NAME}}}
\bibliographystyle{{IEEEtran}}
\bibliography{{{NAME}/{NAME}}}
\end{{document}}
""")
    (OUT / "README.txt").write_text(f"""Section 8 (Experimental Evaluation) of the PaMCP manuscript, journal version (fits the 6-page budget:
pp. 13-17 in the preview plus references).

Contents
  {NAME}.tex          the section (tables inlined; \\label{{sec:ev}}, sec:ev-rq1 ... sec:ev-threats)
  figures/            6 vector figures used by the section
  {NAME}.bib          the 7 references it cites (merge into your .bib if the keys are not already there)
  ../{NAME}_test.tex   (zip root) compiles the section on its own: an optional check

Use in Overleaf
  1. Upload this folder to the project root, next to paper.tex (keep the folder name "{NAME}").
  2. In the preamble of paper.tex (skip what is already there):
       \\usepackage{{graphicx}}
       \\usepackage{{booktabs}}
       \\usepackage{{amsmath}}
       \\usepackage{{url}}
     The section defines \\pamcp only if paper.tex does not (\\providecommand).
  3. Replace the old evaluation section with
       \\input{{{NAME}/{NAME}}}
     placed before the Conclusion.
  4. Add the entries of {NAME}.bib to the paper's bibliography file, or list both files:
       \\bibliography{{paper,{NAME}/{NAME}}}
  5. Cross-references to the rest of the paper used in the text: Fig. 1, Fig. 3, Alg. 1, Definition 6,
     Proposition 1, Proposition 3, Property 1, Eq. (5), Eq. (6), Sections 5 and 6 (written as plain numbers;
     adjust if the manuscript's numbering changes).

All numbers come from results/final/*.json and results/revision_2/*.json of the repository; figures are
regenerated by paper/make_eval_r2.py and this folder by paper/package_overleaf.py.
""")
    zp = OUT.parent / f"{NAME}.zip"
    with zipfile.ZipFile(zp, "w", zipfile.ZIP_DEFLATED) as z:
        for f in sorted(OUT.rglob("*")):
            if f.is_file():
                z.write(f, f.relative_to(OUT.parent))
        z.write(OUT.parent / f"{NAME}_test.tex", f"{NAME}_test.tex")
    print(zp, sum(1 for _ in OUT.rglob("*") if _.is_file()), "files")


if __name__ == "__main__":
    main()
