"""Browser acceptance tests using an already-running TaaS Studio instance.

The Colab runtime notebook owns installation, server startup, token creation
and proxy exposure. This test attaches Playwright to that running endpoint;
it deliberately does not start another Uvicorn process.
"""
from __future__ import annotations

import json
import os
from pathlib import Path
from urllib.parse import urlparse

import pytest


@pytest.mark.parametrize("viewport", [(1440, 1000), (390, 844)])
def test_hypergraph_explorer_on_live_colab_studio(viewport, tmp_path: Path):
    """Attach to the Colab-exposed Studio and validate the real browser journey.

    Required environment:
      TAAS_STUDIO_URL: URL printed/exposed by taas_core_studio_colab.ipynb
      TAAS_STUDIO_API_TOKEN: token generated by that notebook (never print it)

    Browser automation must run in a browser context that can reach the Colab
    proxy URL. No API server or token is created/replaced by this test.
    """
    studio_url = os.environ.get("TAAS_STUDIO_URL", "").strip()
    api_token = os.environ.get("TAAS_STUDIO_API_TOKEN", "").strip()
    if not studio_url or not api_token:
        pytest.skip(
            "Set TAAS_STUDIO_URL to the running Colab proxy URL and "
            "TAAS_STUDIO_API_TOKEN to the current notebook-generated token."
        )

    parsed = urlparse(studio_url)
    if parsed.scheme not in {"http", "https"} or not parsed.netloc:
        pytest.fail("TAAS_STUDIO_URL must be an absolute HTTP(S) Colab proxy URL.")

    try:
        from playwright.sync_api import sync_playwright
    except ImportError:
        pytest.skip("Install Playwright + Chromium in the Colab Runtime first.")

    with sync_playwright() as playwright:
        browser = playwright.chromium.launch(
            headless=True,
            args=["--no-sandbox", "--disable-dev-shm-usage"],
        )
        context = browser.new_context(viewport={"width": viewport[0], "height": viewport[1]})
        page = context.new_page()
        mcp_requests: list[str] = []
        page.on(
            "request",
            lambda request: mcp_requests.append(request.url)
            if "/api/v1/mcp/" in request.url else None,
        )
        try:
            # Separate Colab proxy reachability from the Studio static frontend.
            # A 404 on / can be caused either by the proxy target or by the API's
            # explicit "frontend not installed" response; /health distinguishes them.
            health_url = studio_url.rstrip("/") + "/health"
            health_response = page.request.get(health_url, timeout=30000)
            health_body = health_response.text()
            assert health_response.status == 200, (
                f"Colab proxy did not reach the TaaS API: GET /health returned "
                f"{health_response.status}; body={health_body[:500]!r}. "
                "Check that proxy_url is from the same running Studio process on port 8000."
            )
            response = page.goto(studio_url, wait_until="domcontentloaded", timeout=60000)
            if response is None or response.status != 200:
                body = page.locator("body").inner_text()[:500] if page.locator("body").count() else ""
                pytest.fail(
                    f"TaaS API is reachable (/health=200), but Studio homepage returned "
                    f"{response.status if response else 'no response'}; body={body!r}. "
                    "This points to the static frontend mount/file, not Playwright or the Colab proxy."
                )
            assert page.title() == "TaaS Studio — Tool Intelligence Platform"
            assert page.locator("#hg-empty").is_visible()
            assert page.locator("#hg-filter").is_disabled()

            # Use the exact token produced by the existing Colab launch notebook.
            page.locator("#token").fill(api_token)
            page.locator("#studio-auth-connect").click()
            page.get_by_text("Connected · token verified for this runtime").wait_for(timeout=30000)

            # Run the notebook-provided metadata-only demo discovery in the
            # already-running Studio. No MCP server should be called.
            page.locator("#run").click()
            page.wait_for_function(
                """() => {
                  const status = document.querySelector('#hg-projection-state')?.textContent || '';
                  return status.startsWith('Core projection ·') ||
                         status === 'Projection unavailable' ||
                         status === 'Invalid projection';
                }""",
                timeout=60000,
            )
            result_text = page.locator("#response").inner_text()
            result = json.loads(result_text)
            assert result["execution_performed"] is False
            assert result["hypergraph_projection_status"] == "available", result
            projection = result["hypergraph_projection"]
            assert projection["schema"] == "taas.hypergraph-projection/v1"
            assert projection["vertices"]
            assert projection["hyperedges"]

            page.locator("#hg-workspace").wait_for(state="visible")
            assert page.locator("#hg-filter").is_enabled()
            assert page.locator("#hg-entity-list button").count() > 0
            assert "Rendered directly from the API projection" in page.locator("#hg-status").inner_text()
            assert "No MCP calls or execution performed" in page.locator("#hg-status").inner_text()

            # Filtering is display-only; the immutable API result remains unchanged.
            page.locator("#hg-filter").fill("list_orders")
            visible = page.locator("#hg-entity-list button:visible")
            assert visible.count() >= 1
            for index in range(visible.count()):
                assert "list_orders" in visible.nth(index).inner_text().lower()
            page.locator("#hg-filter").fill("")

            edge = page.locator('.hg-entity[role="button"][aria-label="Inspect tool list_orders"]')
            edge.wait_for(state="visible")
            edge.focus()
            edge.press("Enter")
            assert page.locator("#hg-inspector-title").inner_text() == "list_orders"
            inspector = page.locator("#hg-inspector-body").inner_text()
            assert "Fired in reachability" in inspector
            assert "Fingerprint" in inspector

            page.locator("#hg-entity-list button").filter(has_text="list_orders").first.click()
            assert page.locator("#hg-inspector-title").inner_text() == "list_orders"

            if viewport[0] <= 560:
                columns = page.locator("#hg-workspace").evaluate(
                    "(el) => getComputedStyle(el).gridTemplateColumns"
                )
                assert len(columns.split()) == 1, columns
            assert page.locator("#hg-inspector-title").is_visible()
            assert not mcp_requests, f"Unexpected browser MCP requests: {mcp_requests}"

            screenshot = tmp_path / f"hypergraph-explorer-{viewport[0]}.png"
            page.locator("#hypergraph-explorer").screenshot(path=str(screenshot))
            assert screenshot.is_file() and screenshot.stat().st_size > 0
            artifact_dir = os.environ.get("TAAS_E2E_ARTIFACT_DIR")
            if artifact_dir:
                target = Path(artifact_dir) / screenshot.name
                target.parent.mkdir(parents=True, exist_ok=True)
                target.write_bytes(screenshot.read_bytes())
        finally:
            context.close()
            browser.close()
